function renderWatches() {
    const grid = document.getElementById('watchesGrid');

    watchesBreitling.forEach(watch => {
        const card = document.createElement('div');
        card.className = 'watch-card';
        card.setAttribute('data-watch-id', watch.id);
        card.style.cursor = 'pointer';
        
        card.innerHTML = `
                    <div class="watch-image">
                        <img src="${watch.image}" alt="${watch.model} ${watch.name}">
                    </div>
                    <div class="watch-info">
                        <div class="watch-model">${watch.model}</div>
                        <div class="watch-name">${watch.name}</div>
                        <div class="watch-details">
                            <div class="detail-row">
                                <span class="detail-label">Case</span>
                                <span class="detail-value">${watch.case}</span>
                            </div>
                            <div class="detail-row">
                                <span class="detail-label">Movement</span>
                                <span class="detail-value">${watch.movement}</span>
                            </div>
                            <div class="detail-row">
                                <span class="detail-label">Water Resistance</span>
                                <span class="detail-value">${watch.waterResistance}</span>
                            </div>
                        </div>
                        <div class="watch-price">${watch.price}</div>
                    </div>
                `;
        
        card.addEventListener('click', function() {
            const watchId = this.getAttribute('data-watch-id');
            window.location.href = `single-breitling.html?id=${watchId}`;
        });
        
        grid.appendChild(card);
    });
}

renderWatches();