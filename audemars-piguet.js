function renderWatches() {
    const grid = document.getElementById('watchesGrid');
    grid.innerHTML = watchesPiguet.map(watch => `
                <div class="watch-card" data-watch-id="${watch.id}">
                    <div class="watch-image-container">
                        <img src="${watch.image}" alt="${watch.name}" class="watch-image">
                    </div>
                    <div class="watch-info">
                        <h3 class="watch-name">${watch.name}</h3>
                        <p class="watch-model">${watch.model}</p>
                        <p class="watch-specs">${watch.specs}</p>
                        <div class="watch-footer">
                            <div class="watch-price">${watch.price}</div>
                            <button class="inquire-btn" onclick="event.stopPropagation();">View Model</button>
                        </div>
                    </div>
                </div>
            `).join('');
    document.querySelectorAll('.watch-card').forEach(card => {
        card.addEventListener('click', function() {
            const watchId = this.getAttribute('data-watch-id');
            window.location.href = `single-audemars.html?id=${watchId}`;
        });
        
        card.style.cursor = 'pointer';
    });
    
    document.querySelectorAll('.inquire-btn').forEach(btn => {
        btn.addEventListener('click', function(e) {
            e.stopPropagation();
            const card = this.closest('.watch-card');
            const watchId = card.getAttribute('data-watch-id');
            window.location.href = `single-audemars.html?id=${watchId}`;
        });
    });
}

document.addEventListener('DOMContentLoaded', renderWatches);

document.querySelector('.cta-explore').addEventListener('click', (e) => {
    e.preventDefault();
    document.querySelector('#collection').scrollIntoView({ behavior: 'smooth' });
});